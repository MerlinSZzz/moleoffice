/**
 * THE HISTORY PANEL DRAWS NONE OF ITS FOUR BOXES, IN EITHER MODE, AND PUTS WHERE THE PUT-BACK IS BEHIND ITS "?".
 *
 * Criterion, written before the change.
 *
 * OLD, in developer mode, the History panel on a record's page drew four boxes that each open to a paragraph:
 *   - what putting a version back does, always;
 *   - where the put-back is, when the page is not being edited;
 *   - what was read for the list of everything that happened, always;
 *   - why nothing can be compared with what the record holds now, when no version holds it.
 * Normal mode drew none of them. It drew one sentence under the list saying to press Edit to put an earlier version
 * back, and a plain paragraph when no version holds what the record holds now.
 *
 * NEW, in both modes, on every kind:
 *   - none of the four boxes;
 *   - when the record has more than one version and the header's Edit press opens editing, the panel's heading has a
 *     "?" that holds the one sentence saying to press Edit to put an earlier version back. With one version, while
 *     the page is being edited, and on a deleted record, whose Edit press cannot be pressed, there is no "?";
 *   - when no version holds what the record holds now, a short state line says so, in the page's ordinary text, the
 *     body's size and colour, and not inside a small grey note.
 *
 * WHY: the boxes explain the office's own rules, and explanatory text is taken off the pages, as decided. A hint
 * that is needed is one sentence behind the heading's "?"; a state is a short line.
 *
 * THE RULE ABOVE THE FIRST VERSION ROW. The first row draws no rule when the list is the first thing in the panel, in
 * either mode. It keeps its rule where something stands above the list: the state line saying that no version holds
 * what the record holds now. Every later row keeps its rule.
 *
 * The words are read from the word lists by `t`. The panel does not depend on the kind; the cases draw a note, a
 * report and a task.
 *
 * MADE-UP RECORDS ONLY. The cases start their own test office and file every record through its door as the test
 * office's person. One case changes one reply in the browser and nowhere else: the record read's `revisionSeq` is made
 * null, which is what the server answers when its ledger holds no version with the record's content. Nothing is
 * written to the database for it. No version filed here is a ledger baseline.
 *
 * The test audit table is regenerated by the merge, not by this run.
 */
import type { Page } from 'playwright'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import { createI18n } from '../src/shared/i18n.ts'
import { THE_PERSON } from '../src/shared/person.ts'
import { deleteTheCopiedDefaultChapters, liveApp, type LiveApp, waitForThePage } from './helpers.ts'

const en = createI18n('en').t

const MODES = ['normal', 'inspect'] as const
type Mode = (typeof MODES)[number]

/** The one sentence behind the heading's "?", and the state line when no version holds what the record holds now. */
const PRESS_EDIT = en('record.history.pressEditToPutBack')
const NOT_CURRENT = en('record.history.inNoVersion')

const AS_THE_PERSON: Record<string, string> = {
  'content-type': 'application/json',
  'x-mole-office-workspace': 'default',
  'x-mole-office-actor-type': 'human',
  'x-mole-office-actor-id': THE_PERSON,
}

/** The state line, where the panel draws it. */
interface Said {
  text: string
  /** Inside the panel's small grey note. */
  inANote: boolean
  /** Inside one of the boxes. */
  inABox: boolean
  size: string
  colour: string
}

/** What the History panel draws, read in the browser after both of its lists have been read. */
interface ThePanel {
  versions: number
  boxes: number
  /** What every "?" in the panel holds, in the order they are drawn. */
  hints: string[]
  said: Said[]
  /** The size and colour of the page's ordinary text. */
  body: { size: string; colour: string }
}

let app: LiveApp
let browser: Page
let recordPath: (id: string) => string
let editingAddress: (path: string) => string
const ids = { oneVersion: '', note: '', report: '', task: '', deleted: '' }

async function file(body: unknown): Promise<string> {
  const reply = await fetch(`${app.api}/api/records`, { method: 'POST', headers: AS_THE_PERSON, body: JSON.stringify(body) })
  expect(reply.status, await reply.clone().text()).toBe(201)
  return ((await reply.json()) as { record: { id: string } }).record.id
}

/** A second version, written through the door. */
async function changeOnce(id: string, summary: string): Promise<void> {
  const reply = await fetch(`${app.api}/api/records/${id}`, { method: 'PATCH', headers: AS_THE_PERSON, body: JSON.stringify({ summary }) })
  expect(reply.status, await reply.clone().text()).toBe(200)
}

/** One address in English, in a mode, with the History panel's lists read. */
async function open(address: string, inMode: Mode, editing = false): Promise<ThePanel> {
  await browser.goto(`${app.site}/?lang=en#${address}`, { waitUntil: 'domcontentloaded', timeout: 60_000 })
  await browser.evaluate((chosen) => localStorage.setItem('mole-office.mode', chosen), inMode)
  await browser.reload({ timeout: 60_000 })
  await waitForThePage(browser, 60_000)
  // THE FOLD CARRIES ITS COUNT ONCE THE VERSIONS ARE READ, and the second list has rows once it is read.
  const fold = browser.locator('main.page details.rh-fold[data-versions]')
  await fold.waitFor({ state: 'attached', timeout: 30_000 })
  await fold.locator('.rh-happened').waitFor({ state: 'attached', timeout: 30_000 })
  // WHILE EDITING, THE PANEL MAY WRITE ONLY ONCE THE PAGE HAS READ WHAT ITS PICKERS NEED, and the put-back press on the
  // older version is what shows it may.
  if (editing) await fold.locator('.rh-put-back').first().waitFor({ state: 'attached', timeout: 30_000 })
  return fold.evaluate((one, sentences) => {
    // Opened, so every style below is the style a reader sees.
    ;(one as HTMLDetailsElement).open = true
    const drawnIn = (element: Element) => {
      const style = getComputedStyle(element)
      return { size: style.fontSize, colour: style.color }
    }
    return {
      versions: Number(one.getAttribute('data-versions')),
      boxes: one.querySelectorAll('.px-explain').length,
      hints: Array.from(one.querySelectorAll('.px-hint-body')).map((hint) => (hint.textContent ?? '').trim()),
      said: Array.from(one.querySelectorAll('p'))
        .filter((p) => sentences.includes((p.textContent ?? '').trim()))
        .map((p) => ({ text: (p.textContent ?? '').trim(), inANote: p.closest('.rh-note') !== null, inABox: p.closest('.px-explain') !== null, ...drawnIn(p) })),
      body: drawnIn(document.body),
    }
  }, [NOT_CURRENT])
}

/** How many presses in the header open editing. */
async function editPresses(): Promise<number> {
  return browser.locator('main.page a.rp-mode:not(.rp-mode-done)', { hasText: en('record.edit') }).count()
}

/** A line in the page's ordinary text, outside every note and box. */
function plain(panel: ThePanel, text: string): Said {
  return { text, inANote: false, inABox: false, size: panel.body.size, colour: panel.body.colour }
}

/** The width of the rule above each version row, in the order the rows are drawn. Read after `open`. */
async function rowRules(): Promise<string[]> {
  return browser
    .locator('main.page details.rh-fold .rh-list > .rh-row')
    .evaluateAll((rows) => rows.map((row) => getComputedStyle(row).borderTopWidth))
}

/**
 * Runs `look` while the browser is told that no version of the record holds what it holds now. Only the record read's
 * `revisionSeq` is changed, in this browser, to the null the server answers then.
 */
async function withNoVersionHoldingNow(id: string, look: () => Promise<void>): Promise<void> {
  const read = new RegExp(`/api/records/${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\?[^/]*)?$`)
  await browser.route(read, async (route) => {
    const reply = await route.fetch()
    const body = (await reply.json()) as Record<string, unknown>
    await route.fulfill({ response: reply, json: { ...body, revisionSeq: null } })
  })
  try {
    await look()
  } finally {
    await browser.unroute(read)
  }
}

beforeAll(async () => {
  // THE ROUTER'S MODULES TOUCH `window` WHILE THEY LOAD, so the one global they read is stood up first.
  const store = new Map<string, string>()
  const storage = {
    getItem: (key: string) => store.get(key) ?? null,
    setItem: (key: string, value: string) => void store.set(key, value),
    removeItem: (key: string) => void store.delete(key),
  }
  Object.assign(globalThis, { window: {
    localStorage: storage, sessionStorage: storage, location: { hash: '', search: '' },
    addEventListener: () => {}, removeEventListener: () => {},
  } })
  const router = await import('../src/web/components/router.tsx')
  recordPath = (id) => router.recordPath(id)
  editingAddress = router.editingAddress

  app = await liveApp({ name: 'history-panel-boxes', viewport: { width: 1440, height: 1000 }, workspace: 'default' })
  browser = app.page
  await deleteTheCopiedDefaultChapters(app.api)
  ids.oneVersion = await file({ kind: 'note', title: 'The made-up kiln shelf was moved once', data: {} })
  ids.note = await file({ kind: 'note', title: 'The made-up kiln shelf was moved twice', data: {} })
  await changeOnce(ids.note, 'The shelf went to the second rack.')
  ids.report = await file({
    kind: 'report', title: 'The made-up glaze tiles for October',
    data: { for: 'the glaze room', date: '2026-10-02', blocks: [{ id: 'one', type: 'text', text: 'Nine made-up glaze tiles were fired.' }] },
  })
  await changeOnce(ids.report, 'Nine tiles fired, two crawled.')
  ids.task = await file({ kind: 'task', title: 'Order the made-up cone pack', data: {} })
  await changeOnce(ids.task, 'Cones 6 and 7.')
  ids.deleted = await file({ kind: 'note', title: 'The made-up kiln log nobody keeps', data: {} })
  await changeOnce(ids.deleted, 'It was kept for a week.')
  const gone = await fetch(`${app.api}/api/records/${ids.deleted}`, { method: 'DELETE', headers: AS_THE_PERSON })
  expect(gone.ok, await gone.clone().text()).toBe(true)
}, 300_000)

afterAll(async () => {
  await app?.stop()
}, 120_000)

describe('the History panel in both modes', () => {
  it('draws no box, and the sentence behind the heading\'s "?", on a record with two versions that is being read', async () => {
    for (const [kind, id] of [['note', ids.note], ['report', ids.report], ['task', ids.task]] as const) {
      for (const mode of MODES) {
        const panel = await open(recordPath(id), mode)
        expect(panel.versions, `${kind}, ${mode}: the versions this case needs`).toBe(2)
        expect(panel.boxes, `${kind}, ${mode}: the boxes drawn`).toBe(0)
        expect(panel.hints, `${kind}, ${mode}: what the "?" holds`).toEqual([PRESS_EDIT])
        expect(panel.said, `${kind}, ${mode}: a state line drawn`).toEqual([])
        expect(await editPresses(), `${kind}, ${mode}: the Edit press the sentence names`).toBe(1)
      }
    }
  }, 300_000)

  it('draws no box and no "?" while the page is being edited', async () => {
    const editing = editingAddress(recordPath(ids.note))
    for (const mode of MODES) {
      const panel = await open(editing, mode, true)
      expect(panel.versions, `${mode}: the versions this case needs`).toBe(2)
      expect(panel.boxes, `${mode}: the boxes drawn`).toBe(0)
      expect(panel.hints, `${mode}: a "?" drawn while editing`).toEqual([])
    }
  }, 300_000)

  it('draws no box and no "?" on a record with one version', async () => {
    for (const mode of MODES) {
      const panel = await open(recordPath(ids.oneVersion), mode)
      expect(panel.versions, `${mode}: the versions this case needs`).toBe(1)
      expect(panel.boxes, `${mode}: the boxes drawn`).toBe(0)
      expect(panel.hints, `${mode}: a "?" drawn with one version`).toEqual([])
    }
  }, 300_000)

  it('draws no "?" on a deleted record, whose Edit press cannot be pressed', async () => {
    for (const mode of MODES) {
      const panel = await open(recordPath(ids.deleted), mode)
      expect(panel.versions, `${mode}: the versions this case needs`).toBeGreaterThan(1)
      expect(await editPresses(), `${mode}: an Edit press that opens editing on a deleted record`).toBe(0)
      expect(panel.boxes, `${mode}: the boxes drawn`).toBe(0)
      expect(panel.hints, `${mode}: the "?" names a press that cannot be pressed`).toEqual([])
    }
  }, 300_000)

  it('draws a plain state line when no version holds what the record holds now, in both modes', async () => {
    await withNoVersionHoldingNow(ids.note, async () => {
      for (const mode of MODES) {
        const panel = await open(recordPath(ids.note), mode)
        expect(panel.boxes, `${mode}: the boxes drawn`).toBe(0)
        expect(panel.said, `${mode}: the state line, in the page's ordinary text`).toEqual([plain(panel, NOT_CURRENT)])
        expect(panel.hints, `${mode}: what the "?" holds`).toEqual([PRESS_EDIT])
      }
    })
  }, 300_000)

  it('draws no rule above the first version row when the list is the first thing in the panel, and keeps every other rule', async () => {
    for (const mode of MODES) {
      const panel = await open(recordPath(ids.note), mode)
      expect(panel.versions, `${mode}: the versions this case needs`).toBe(2)
      expect(await rowRules(), `${mode}: the rule above each version row`).toEqual(['0px', '1px'])
    }

    await withNoVersionHoldingNow(ids.note, async () => {
      const notCurrent = await open(recordPath(ids.note), 'normal')
      expect(notCurrent.said.map((said) => said.text), 'normal: the state line above the list').toEqual([NOT_CURRENT])
      expect(await rowRules(), 'normal: the rule above each version row, the first under the state line').toEqual(['1px', '1px'])
    })
  }, 300_000)
})
