/**
 * COMMON LATEX, AS PEOPLE WRITE IT IN PAPERS AND NOTES: the corpus that
 * tests/common-latex-is-drawn.test.ts draws, and the list the reference comparison with MathJax reads.
 *
 * Each family is one kind of construct. An expression in `inline` is drawn as it would be inside a
 * sentence, and one in `display` as a displayed block, because some constructs are only written in
 * one of the two (an `align*` is display maths in LaTeX itself). Every expression here is one a
 * person could have typed: nothing is made to pass, and nothing is made to fail.
 *
 * TWELVE HARD FORMULAS close the file. They are ordinary textbook mathematics and physics, written
 * for this file, and between them they hold a tilde over a letter, big brackets and parentheses,
 * `\mathcal`, `\mathbf` with subscripts, superscripts and an inverse, `\doteq`, a named operator, a
 * transpose, `\tfrac`, `\boldsymbol` and a row vector in brackets.
 */

export interface AFamily {
  /** What the family is, as the test case names it. */
  readonly family: string
  readonly inline: readonly string[]
  readonly display: readonly string[]
}

