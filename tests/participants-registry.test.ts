/**
 * THE TWO REGISTRIES: what the migration puts in them, and what the record door keeps in them.
 *
 * Criterion M2 of design/messages/ACCEPTANCE.md — *People and durable agents are participants. Each
 * registry is its own table, not a project record … Every existing `agent` record maps to one
 * registry row by handle, and the project records are kept and linked, not deleted* — and the
 * registry half of M14, which is the lookup of the actor id on a request.
 *
 * WHAT IS DELIBERATELY NOT HERE. The avatar drawing, the routes and the screens are their own
 * commits with their own tests. This file is about the rows.
 */

import { THE_TEST_OFFICES_OWNER } from './a-page-of-a-test-office.ts'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { freshDb, type TestDb } from './helpers.ts'
import { THE_PERSON } from '../src/shared/person.ts'
import { AGENT_RUNTIMES, defaultAvatarAssetId } from '../src/shared/participants.ts'

type MigrationLib = typeof import('../src/server/db/participants-migration.ts')
type RegistryLib = typeof import('../src/server/lib/participants.ts')
type MigrateLib = typeof import('../src/server/db/migrate.ts')

let t: TestDb
/**
 * IMPORTED AFTER `freshDb()`, NEVER AT THE TOP OF THE FILE. Everything under src/server/lib opens
 * MOLE_OFFICE_DB the moment it is imported, and `freshDb` is what points that at a throwaway file —
 * so a static import here would open the operator's own database, which src/server/db/client.ts
 * refuses under a test runner and says so.
 */
let migration: MigrationLib
let registry: RegistryLib
let migrate: MigrateLib

const HUMAN = { type: 'human', id: THE_PERSON } as const

beforeEach(async () => {
  t = await freshDb()
  migration = await import('../src/server/db/participants-migration.ts')
  registry = await import('../src/server/lib/participants.ts')
  migrate = await import('../src/server/db/migrate.ts')
})

afterEach(() => {
  t.close()
})

/** One row of a table, as SQLite hands it back. */
function row(sql: string, ...params: unknown[]): Record<string, unknown> | undefined {
  return t.client.sqlite.prepare(sql).get(...params) as Record<string, unknown> | undefined
}

function count(table: string): number {
  return (t.client.sqlite.prepare(`SELECT count(*) AS n FROM ${table}`).get() as { n: number }).n
}

/**
 * Write a record of kind `agent` straight at the table, WITHOUT the door.
 *
 * This is what a database written before the registry existed holds, and it is the only way to reach
 * the state the migration is for: the door registers an agent the moment its record is created, so a
 * record made through `createRecord` is already mapped and the migration would have nothing to do.
 */
function anAgentRecordFromBefore(id: string, workspaceId: string, title: string, data: object, at: string): void {
  t.client.sqlite
    .prepare(
      'INSERT INTO records (id, workspace_id, owner_id, created_at, updated_at, kind, title, summary, data, origin) ' +
        `VALUES (?, ?, '${THE_TEST_OFFICES_OWNER.id}', ?, ?, 'agent', ?, NULL, ?, 'authored')`,
    )
    .run(id, workspaceId, at, at, title, JSON.stringify(data))
}

// ============================================================ what the migration puts in the tables

describe('the migration writes the owner and every durable agent this database already names', () => {
  it('writes exactly one person, with the id every change row in this database already uses', () => {
    // NOT A NEW NAME FOR THE PERSON. `THE_PERSON` is the id on the person's rows, on the change log and in the
    // authority guard, so the registry row and the history name the same person. A registry that
    // minted its own id for the person would leave every existing row attributed to somebody the registry
    // does not know.
    expect(count('people')).toBe(1)
    const person = row('SELECT * FROM people')
    expect(person?.['id']).toBe(THE_PERSON)
    expect(person?.['handle']).toBe(THE_PERSON)
    expect(person?.['name']).toBe(THE_TEST_OFFICES_OWNER.name)
    // NOTHING ELSE IS INVENTED. Nobody has set a state, and nobody recorded who created this row —
    // a migration wrote it and no participant asked for it.
    expect(person?.['state']).toBeNull()
    expect(person?.['state_at']).toBeNull()
    expect(person?.['created_by_kind']).toBeNull()
    expect(person?.['created_by_id']).toBeNull()
  })

  it('draws the person a picture, says this product made it, and stores no file for it', () => {
    const asset = row('SELECT * FROM assets WHERE id = ?', defaultAvatarAssetId({ kind: 'person', id: THE_PERSON }))
    expect(asset, 'the owner has no picture').toBeDefined()
    expect(asset?.['origin']).toBe('default')
    expect(asset?.['licence_source']).toBe('generated by Mole Office')
    // NO FILE AND NO SIZE. The drawing is worked out from the id when it is asked for, so there is
    // nothing on disk to measure and both columns say so rather than holding a zero.
    expect(asset?.['path']).toBeNull()
    expect(asset?.['bytes']).toBeNull()
    expect(row('SELECT avatar_asset_id FROM people WHERE id = ?', THE_PERSON)?.['avatar_asset_id']).toBe(asset?.['id'])
  })

  it('maps an agent record written before the registry existed, and keeps the record', () => {
    anAgentRecordFromBefore('rec-old-1', 'panelx', 'Round ten', { handle: 'round-ten', state: 'active' }, '2026-08-01 09:00:00')

    const report = migration.migrateParticipants(t.client.sqlite)

    expect(report.agentsWritten).toBe(1)
    expect(report.recordsMapped).toBe(1)
    const agent = registry.agentByHandle('round-ten')
    expect(agent?.name).toBe('Round ten')
    // THE IDENTITY IS AS OLD AS THE RECORD THAT NAMED IT, not as old as the migration. Stamping it
    // with this run's clock would say every agent in the corpus was created the day the registry
    // arrived, which is a fact about the migration and not about the agent.
    expect(agent?.createdAt).toBe('2026-08-01 09:00:00')
    // AND THE RECORD IS STILL THERE. An inbox, a conversation and a work domain all point at it.
    expect(row('SELECT id FROM records WHERE id = ?', 'rec-old-1')).toBeDefined()
    expect(registry.agentForRecord('rec-old-1')?.handle).toBe('round-ten')
  })

  it('leaves the registry runtime empty for a word nobody declared, keeps the record, and says so', () => {
    // `codex-cli` is the word the `agent` record kind documented before the three M2 names became a
    // checked list. Two things must both be true. The RECORD keeps its own word: rewriting a stored
    // value to make a list look tidy is the one thing a migration here may not do, and `codex-cli`
    // must not quietly become `codex`. The registry COLUMN stays empty: it means which of the three
    // runtimes serves this agent, and no answer is a true one here. Problem `3zYuz90LvTS5`.
    anAgentRecordFromBefore('rec-old-2', 'panelx', 'The other one', { handle: 'other', runtime: 'codex-cli', state: 'active' }, '2026-08-02 09:00:00')

    const report = migration.migrateParticipants(t.client.sqlite)

    expect(registry.agentByHandle('other')?.runtime).toBeNull()
    expect(row("SELECT json_extract(data, '$.runtime') AS runtime FROM records WHERE id = ?", 'rec-old-2')).toEqual({
      runtime: 'codex-cli',
    })
    // AND IT IS SAID OUT LOUD. An empty column reads exactly like a record that never named a
    // runtime, and those are two different facts.
    expect(report.runtimesNobodyDeclared).toEqual([{ handle: 'other', said: 'codex-cli' }])
    const said = migration.describeParticipants(report)
    expect(said).toContain('other')
    expect(said).toContain('codex-cli')
  })

  it('carries a retired agent across as retired, with the reason the record gave', () => {
    anAgentRecordFromBefore(
      'rec-old-3',
      'panelx',
      'Round nine',
      { handle: 'round-nine', state: 'retired', retiredBecause: 'The round nine campaign finished.' },
      '2026-08-03 09:00:00',
    )

    migration.migrateParticipants(t.client.sqlite)

    // A RETIRED AGENT, read the way an arriving name is read: `agentByHandle` answers only a LIVE agent
    // since criterion I3, and the resolver answers the one retired agent bearing the name for a read.
    const agent = registry.theRowAnArrivingReferenceNames('round-nine', 'reading')
    expect(agent?.retired).toBe(true)
    expect(agent?.retiredBecause).toBe('The round nine campaign finished.')
  })

  it('gives two projects sharing one handle one registry row, and says so', async () => {
    // WHAT "BY HANDLE" MEANS, MEASURED. A handle is unique inside a project and not across the
    // installation, so this really happens. The report names it rather than leaving somebody to
    // notice that two records answer to one row.
    const workspaces = (await import('../src/server/lib/workspaces.ts')) as typeof import('../src/server/lib/workspaces.ts')
    workspaces.createWorkspace({ id: 'robotics', title: 'Robotics' })
    anAgentRecordFromBefore('rec-a', 'panelx', 'Builder here', { handle: 'builder', state: 'active' }, '2026-08-01 09:00:00')
    anAgentRecordFromBefore('rec-b', 'robotics', 'Builder there', { handle: 'builder', state: 'active' }, '2026-08-02 09:00:00')

    const report = migration.migrateParticipants(t.client.sqlite)

    expect(report.agentsWritten).toBe(1)
    expect(report.recordsMapped).toBe(2)
    expect(report.handlesSharedAcrossRecords).toEqual(['builder'])
    expect(registry.agentForRecord('rec-a')?.id).toBe(registry.agentForRecord('rec-b')?.id)
    expect(migration.describeParticipants(report)).toContain('more than one')
  })

  it('leaves a record whose handle nothing can use unmapped, and names it', () => {
    // ABSENCE BEATS A GUESS. Inventing a handle would put an address into the registry that nobody
    // chose and that another agent may later ask for.
    anAgentRecordFromBefore('rec-bad', 'panelx', 'No address', { handle: 'NOT A HANDLE', state: 'active' }, '2026-08-04 09:00:00')

    const report = migration.migrateParticipants(t.client.sqlite)

    expect(report.agentsWritten).toBe(0)
    expect(report.recordsMapped).toBe(0)
    expect(report.refused.map((r) => r.recordId)).toEqual(['rec-bad'])
    expect(registry.agentForRecord('rec-bad')).toBeNull()
    expect(migration.describeParticipants(report)).toContain('rec-bad')
  })

  it('writes nothing the second time it runs', () => {
    anAgentRecordFromBefore('rec-old-4', 'panelx', 'Round ten', { handle: 'round-ten', state: 'active' }, '2026-08-01 09:00:00')
    migration.migrateParticipants(t.client.sqlite)
    const before = [count('people'), count('agents'), count('assets'), count('agent_records')]

    const again = migration.migrateParticipants(t.client.sqlite)

    expect([again.ownerWritten, again.agentsWritten, again.avatarsWritten, again.recordsMapped]).toEqual([0, 0, 0, 0])
    expect([count('people'), count('agents'), count('assets'), count('agent_records')]).toEqual(before)
    expect(migration.describeParticipants(again)).toContain('Nothing to do')
  })
})

// ============================================================ the door, and why it has to be a door

describe('a durable agent written today gets its registry row at the door', () => {
  it('registers the agent as the record is written, with its picture and its mapping', () => {
    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })

    const agent = registry.agentForRecord(made.id)
    expect(agent?.handle).toBe('builder-x')
    expect(agent?.name).toBe('Builder X')
    expect(agent?.runtime).toBe('claude-code')
    // AND IT WAS GIVEN THE PICTURE IT WAS OFFERED, rather than left on the drawing. The owner's
    // decision `HnoPsajfgR0A`, 4 September 2026: an agent that chose no picture when it registered
    // takes the recommended one, nobody asked. It is stored the way a picture pressed in the picker
    // is, because it goes through the same door.
    // The drawing is named for the registry id, which the door mints and which is not the handle.
    expect(agent?.id, 'the door gave the agent its handle as its id, not a minted id').not.toBe('builder-x')
    const drawing = defaultAvatarAssetId({ kind: 'agent', id: agent!.id })
    expect(agent?.avatarAssetId, 'the agent was left on the drawing rather than given a picture').not.toBe(drawing)
    expect(row('SELECT origin FROM assets WHERE id = ?', agent?.avatarAssetId)?.['origin']).toBe('uploaded')
    // AND THE DRAWING IS STILL THERE, so a person may go back to it: it is not deleted, only unused.
    expect(row('SELECT origin FROM assets WHERE id = ?', drawing)?.['origin']).toBe('default')
  })

  it('refuses a runtime word nobody declared, and the refusal names every one it does declare', () => {
    // WHAT THIS IS ABOUT. `AGENT_RUNTIMES` was declared, its comment said a new write was checked
    // against it, and nothing in the repository imported it: `runtime: "a-runtime-nobody-declared"`
    // was accepted and the registry row carried that string. Problem `3zYuz90LvTS5`. The worker in
    // part 2d picks its adapter from this field, so a word nobody declared picks none.
    let said = ''
    try {
      t.api.createRecord({
        workspaceId: 'panelx',
        kind: 'agent',
        title: 'Builder X',
        data: { handle: 'builder-x', runtime: 'a-runtime-nobody-declared', state: 'active' },
        actor: HUMAN,
      })
    } catch (err) {
      said = err instanceof Error ? err.message : String(err)
    }

    expect(said, 'the write was allowed, and this test is about it being refused').not.toBe('')
    for (const word of AGENT_RUNTIMES) expect(said).toContain(word)
    // AND NOTHING WAS WRITTEN, on either side of the door.
    // NO ROW AT ALL, live or retired: `agentByHandle` sees only a live one since criterion I3.
    expect(row('SELECT count(*) AS n FROM agents WHERE handle = ?', 'builder-x')).toEqual({ n: 0 })
    expect(row("SELECT count(*) AS n FROM records WHERE kind = 'agent'")).toEqual({ n: 0 })
  })

  it('accepts each of the words the list declares', () => {
    for (const word of AGENT_RUNTIMES) {
      const made = t.api.createRecord({
        workspaceId: 'panelx',
        kind: 'agent',
        title: `Served by ${word}`,
        data: { handle: `served-by-${word}`, runtime: word, state: 'active' },
        actor: HUMAN,
      })

      expect(registry.agentForRecord(made.id)?.runtime, `${word} is on the list and was refused`).toBe(word)
    }
  })

  it('leaves a server able to start, which is the whole reason it is a door', () => {
    // MEASURED BEHAVIOUR, NOT A PREFERENCE. A database holding work with a migration still to write
    // something is one `prepareToServe` refuses. So an agent record created through the API and left
    // unmapped would take the next server start down — under `tsx watch`, the next time anybody saves
    // a server file. The same shape was measured on 31 August 2026 for a comment's recipient.
    t.api.createRecord({ workspaceId: 'panelx', kind: 'task', title: 'Real work nobody would want to lose', actor: HUMAN })
    t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })

    const decision = migrate.prepareToServe(t.client.sqlite)

    expect(decision.serve, decision.serve ? '' : decision.refusal).toBe(true)
  })

  it('follows a renamed handle, because a handle is an address', () => {
    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })

    const id = registry.agentForRecord(made.id)?.id
    expect(id, 'the door wrote no registry row for the agent').toBeDefined()

    t.api.patchRecord(made.id, { dataPatch: { handle: 'builder-ten' } }, HUMAN)

    expect(registry.agentForRecord(made.id)?.handle).toBe('builder-ten')
    // AND THE ID DOES NOT MOVE. An id is opaque once written, and everything already addressed to
    // this agent names it.
    expect(registry.agentForRecord(made.id)?.id).toBe(id)
  })

  it('follows retirement, because the record and the registry hold one fact in two places', () => {
    // UNTIL PART 2B MOVES THE MESSAGES, the record's `state` is what the existing inbox reads and
    // the registry's `retired` is what the chat will read. Two copies with nothing making them agree
    // is the defect CLAUDE.md names as this repository's own; the door derives one from the other,
    // which is the third of that rule's three answers.
    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })
    expect(registry.agentForRecord(made.id)?.retired).toBe(false)

    t.api.patchRecord(
      made.id,
      { dataPatch: { state: 'retired', retiredBecause: 'The campaign it was for finished.' } },
      HUMAN,
    )

    expect(registry.agentForRecord(made.id)?.retired).toBe(true)
    expect(registry.agentForRecord(made.id)?.retiredBecause).toBe('The campaign it was for finished.')

    // AND BACK, because a retired agent can be made active again and the two must still agree.
    t.api.patchRecord(made.id, { dataPatch: { state: 'active' } }, HUMAN)
    expect(registry.agentForRecord(made.id)?.retired).toBe(false)
    expect(registry.agentForRecord(made.id)?.retiredBecause).toBeNull()
  })

  it('does not overwrite a name a person chose, when the record is retitled', () => {
    // M3 gives a person the right to change any agent's name. A door that copied the record's title
    // over it would undo that edit the next time anybody touched the record.
    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })
    const changed = t.client.sqlite
      .prepare('UPDATE agents SET name = ? WHERE id = ?')
      .run('The one that reads code', registry.agentForRecord(made.id)!.id)
    expect(changed.changes, 'the person\'s name change reached no registry row').toBe(1)

    t.api.patchRecord(made.id, { title: 'Builder X, second run' }, HUMAN)

    expect(registry.agentForRecord(made.id)?.name).toBe('The one that reads code')
  })
})

// ============================================================ M14, the registry half of who is calling

describe('the actor id on a request is looked up in the registries', () => {
  it('finds the person by the id the person’s own rows carry', () => {
    expect(registry.participantForActor({ type: 'human', id: THE_PERSON })).toEqual({ kind: 'person', id: THE_PERSON })
  })

  it('finds a registered agent by its id and by its handle, which are what a caller types', () => {
    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'agent',
      title: 'Builder X',
      data: { handle: 'builder-x', runtime: 'claude-code', state: 'active' },
      actor: HUMAN,
    })
    // The door minted the registry id, so it is read from the registry rather than assumed.
    const id = registry.agentForRecord(made.id)!.id
    expect(id, 'the door gave the agent its handle as its id, not a minted id').not.toBe('builder-x')

    expect(registry.participantForActor({ type: 'agent', id: 'builder-x' })).toEqual({ kind: 'agent', id })
    expect(registry.participantForActor({ type: 'agent', id })).toEqual({ kind: 'agent', id })
  })

  it('answers nobody for an agent nothing has registered, and refuses nothing for it', () => {
    // The owner's F1 answer of 3 September 2026, applied to identity: name it, never stop it. A write
    // from an unregistered agent is accepted exactly as it was before the registry existed, and null
    // here is what the surfaces draw as unregistered with its own id.
    expect(registry.participantForActor({ type: 'agent', id: 'claude-code/nobody-registered' })).toBeNull()

    const made = t.api.createRecord({
      workspaceId: 'panelx',
      kind: 'note',
      title: 'Written by an agent nobody registered',
      actor: { type: 'agent', id: 'claude-code/nobody-registered' },
    })

    expect(made.title).toBe('Written by an agent nobody registered')
  })

  it('answers nobody for a person nothing has registered, rather than taking the header at its word', () => {
    expect(registry.participantForActor({ type: 'human', id: 'somebody-else' })).toBeNull()
  })
})
