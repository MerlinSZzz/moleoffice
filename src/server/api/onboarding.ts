/**
 * THE READ A NEW AGENT MAKES FIRST: WHICH DOORS, AND WHICH PROJECT.
 *
 * ---------------------------------------------------------------------------------------
 * WHAT IT IS, AND HOW IT DIFFERS FROM THE READS BESIDE IT
 * ---------------------------------------------------------------------------------------
 *
 * `GET /api/project/bootstrap` answers *what is true of this project and what contradicts itself*.
 * `GET /api/brief` answers *what to work on and how to write here*. `GET /api` answers *what can be
 * asked for*, and `GET /api/kinds` answers *what a record may hold*. None of them answers *which
 * handful of doors do I knock on, and which project am I in* — and together they cost about
 * 256,000 estimated tokens, a start that was refused.
 *
 * This answers the doors and the project and nothing else. Its budget is three thousand estimated
 * tokens, criterion F15. It does not restate the brief: a test pins that this reply carries no
 * module list, no open-work list and no decisions.
 *
 * AND, WHEN A DIRECTORY IS NAMED, WHO IS REGISTERED AS STARTING IN IT, by part (c) of
 * a decision.
 * The session hook already makes this read for the project, so the folder's agents ride along in it
 * rather than costing the hook a sixth request inside its ten-second timeout. It carries the facts and
 * never the choice: the hook decides who it names, because the hook is what knows whether the session
 * it is filing for is the one already answering.
 *
 * ---------------------------------------------------------------------------------------
 * EVERY DOOR'S SENTENCE IS THE ROUTE'S OWN
 * ---------------------------------------------------------------------------------------
 *
 * The reply carries a route and that route's own description, cut to its first sentence. It is not
 * a second sentence about the route — that would be the same fact written in two places, free to
 * drift, in the one reply a cold agent trusts. A door named here that the server does not serve is
 * refused rather than quietly dropped, and `tests/onboarding-read.test.ts` walks the live route
 * table and holds the same thing.
 *
 * ---------------------------------------------------------------------------------------
 * IT MEASURES ITSELF, AND IT NAMES WHAT IT DROPPED
 * ---------------------------------------------------------------------------------------
 *
 * The handler serialises the reply, counts it, and — while it is over budget — drops one rung of
 * `ONBOARDING_LADDER` at a time. Every rung it drops is named in `leftOut` with the request that
 * fetches the thing back. A reply that fits drops nothing and says so, which is a real answer and
 * not an absence.
 *
 * The size is in characters and bytes, which are counted, and in tokens, which are not. No
 * tokenizer is installed here, so every token figure is characters divided by `CHARS_PER_TOKEN`,
 * it is named `tokensEstimated`, and `size.tokensAreAnEstimate` says in a sentence that no
 * tokenizer ran. The budget is checked against that estimate.
 *
 * ---------------------------------------------------------------------------------------
 * THE COMPACT KIND READ IS A SIBLING, NOT A SECOND DECLARATION
 * ---------------------------------------------------------------------------------------
 *
 * `GET /api/kinds/:kind/compact` carries one kind's field names with each one's type, and the
 * names of the required ones, and no prose. It is generated by `compactKindOf` from the same `KIND_SPECS` the full
 * read is generated from, so the cheap read cannot disagree with the true one. The nested shapes
 * the full read adds are deliberately absent, and the full route is the one that fetches them.
 */
