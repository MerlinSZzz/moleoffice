/** What a route group needs to answer: the live route table, read per request. */
export interface OnboardingOptions {
  listRoutes: () => readonly ApiRoute[]
  /** The address of the office's own page, as the person's browser reaches it, for the guide's address. */
  pageAddress: (req: FastifyRequest) => string
}

/**
 * WHO OWNS THIS OFFICE, FIRST IN THE READ WHILE NOBODY HAS GIVEN A NAME. Point (b) of
 * a decision says an agent that downloads or installs the office for a person, starting from
 * nothing, should be able to open the newcomer guide for them. This read is the first thing such an
 * agent makes, so it says plainly that the office has no owner yet, where the guide is, and what the
 * agent does: open it for the person or hand them the link, and never give the name itself.
 */
function theOwnerReading(guideAt: string): Record<string, unknown> {
  const owner = theOfficeOwner()
  if (owner.name !== null) return { named: true, id: owner.id, name: owner.name }
  return {
    named: false,
    id: owner.id,
    guide: guideAt,
    says:
      `This office has no owner yet. The guide is at ${guideAt}. Open it for the person, or hand them the link. ` +
      'Never fill in their name for them: only the person names themselves, and the office refuses an agent that tries.',
  }
}

/** One door, as the reply carries it: the route, and that route's own first sentence. */
interface OnboardingDoor {
  route: string
  what: string
}

/** What this reply says about its own size. */
interface OnboardingSize {
  characters: number
  bytes: number
  tokensEstimated: number
  charsPerTokenAssumed: number
  budgetTokensEstimated: number
  fits: boolean
  tokensAreAnEstimate: string
}

/** The project this read worked out, and how. */
interface OnboardingProject {
  id: string | null
  title: string | null
  howWorkedOut: string
  asked: { workspaceHeader: boolean; directory: string | null }
  note: string
}

/** One live agent registered as starting in the folder asked about, and where it is already answering. */
interface AnAgentStartingHere {
  handle: string
  /**
   * The record of the live session this agent is already answering in, or null because none is.
   *
   * `whoIsAnsweringAs` is the reading, and only its `a live session` answer counts here. A run the
   * office started is not a session somebody has open, and the session hook's rule is about a person's
   * terminal: the answer to open question 11 of the recognition measurement.
   */
  answeringIn: string | null
}

/** What this read says about the folder it was asked about. */
interface OnboardingStartFolder {
  /** The folder the agents were looked up by, in the spelling the office stores, or null because no directory was named. */
  directory: string | null
  /** Every live agent registered as starting in exactly that folder, or null because nothing was looked up. */
  agents: AnAgentStartingHere[] | null
  note: string
}

/**
 * WHICH DURABLE AGENTS SAY THEIR SESSIONS START IN THIS FOLDER, by part (c) of
 * a decision.
 *
 * The session hook reads this when neither the session's environment nor a `.env` names an agent. It
 * carries the facts and never the choice: WHO IS NAMED IS THE HOOK'S OWN SENTENCE, because the hook is
 * what knows whether the session it is filing for is the one already answering.
 *
 * NOTHING LOOKED UP AND NOBODY FOUND ARE DIFFERENT ANSWERS. A request with no directory gets
 * `agents: null`, because no folder was asked about; a directory nobody registered gets an empty list.
 * An agent told "nobody" when nobody looked would claim a name on no evidence.
 */
async function theStartFolderReading(directory: string | null): Promise<OnboardingStartFolder> {
  if (directory === null) {
    return {
      directory: null,
      agents: null,
      note: 'No directory was named, so no start folder was looked up and nothing here says anything about one.',
    }
  }
  // A FOLDER NO AGENT COULD BE REGISTERED IN IS ANSWERED WITH THE REASON, and with an empty list rather
  // than a null: nothing is registered there, which is a fact, not a folder nobody looked at. A home
  // folder and the root of the machine land here, which is the ordinary case for a session a person
  // started in their own home.
  const asked = theStartFolderAsItIsStored(directory)
  if (asked.folder === null) {
    return {
      directory,
      agents: [],
      note: `No agent can be registered as starting in this folder. ${String(asked.because)}`,
    }
  }
  // THE AGENT'S OWN PROJECT, NOT THE ASKER'S. A hold is the installation's and this read may be made
  // from a directory in another project, exactly as the presence reading says of itself. The agent
  // was found through its own record, so that record's project is always there.
  const registered = agentsStartingIn(asked.folder).map((one) => ({ one, project: theProjectOfTheAgentRecord(one.id) }))
  const whetherEachAnswers = () => registered.map(({ one, project }) => {
    const answering = project === null ? null : whoIsAnsweringAs(one.id, project)
    return {
      handle: one.handle,
      answeringIn: answering !== null && answering.how === 'a live session' ? answering.session : null,
    }
  })
  // WHETHER EACH ANSWERS IS READ ON ONE READING OF EVERY PROCESS, made without holding the thread (Windows;
  // `readEveryProcessFirst` in src/config/session-process.mjs), and only when the reading for one of them will ask
  // about a process.
  const found = registered.some(({ one, project }) => project !== null && whoIsAnsweringAsAsksAboutAProcess(one.id, project))
    ? await readEveryProcessFirst(whetherEachAnswers)
    : whetherEachAnswers()
  return {
    directory: asked.folder,
    agents: found,
    note:
      found.length === 0
        ? 'No live agent is registered as starting in this folder.'
        : `${String(found.length)} live agent${found.length === 1 ? '' : 's'} registered this exact folder. A ` +
          'session started here is named as one of them only when it is the only one and it is not already ' +
          'answering in another live session.',
  }
}

/** The read takes one optional option: the working directory to match a project against. */
const onboardingQuery = z.strictObject({
  directory: z
    .string({ error: 'directory is the absolute path this session was started in' })
    .trim()
    .min(1, { error: 'directory must not be empty — leave it out rather than sending spaces' })
    .optional(),
})

/** What the compact kind read declares about itself, in the route table and on GET /api. */
const COMPACT_KIND_NOTE =
  'ONE KIND\'S FIELD SPEC, CHEAPLY: {kind, required, fields}. `fields` names every field of the kind ' +
  'as a key whose value is the field\'s type, and `required` lists the keys of the fields the kind needs. ' +
  'No prose — no description, no example and no rules. Generated from the same declaration the full ' +
  'read is generated from, so the two cannot disagree. At most a thousand estimated tokens for ' +
  '`session`, the largest kind; GET /api/kinds/session costs many times that. It does NOT carry the nested ' +
  'shapes a field may mention; GET /api/kinds/:kind carries those.'

/**
 * WHICH PROJECT THIS REQUEST IS ABOUT, AND THE SENTENCE SAYING HOW IT WAS WORKED OUT.
 *
 * `resolveProject` in src/server/lib/onboarding.ts is the one reading. A stated header wins. A
 * named working directory is matched against the repositories and work areas registered to each
 * project, deepest match first. Nothing matched is an absence and is said as one: this read names
 * no project and asks which, and never falls back to the default.
 */

/**
 * THE ROUTE'S OWN SENTENCE FOR ONE DOOR, or a refusal if the door is not served.
 *
 * `route.note` is what the route declared beside itself; the maps hold the lines for the older
 * route groups. Both are the server's own account of the endpoint. A door with neither is an
 * endpoint nobody has described, and this read will not invent one.
 */
function sentenceForDoor(routeKey: string, routes: readonly ApiRoute[]): string {
  const found = routes.find((candidate) => `${candidate.method} ${candidate.path}` === routeKey)
  if (found === undefined) {
    throw new PanelError(
      `The onboarding read names a door this server does not serve: ${routeKey}. The doors are declared in ` +
        'ONBOARDING_DOORS in src/shared/onboarding.ts; remove the door or register the route.',
      500,
    )
  }
  const description = found.note ?? ALL_ROUTE_NOTES[routeKey] ?? null
  if (description === null) {
    throw new PanelError(
      `The onboarding read names ${routeKey}, which this server serves and nobody has described. Add the ` +
        'sentence beside the route or to ALL_ROUTE_NOTES in src/server/api/kinds.ts.',
      500,
    )
  }
  return firstSentenceOf(description)
}

export async function onboardingRoutes(app: FastifyInstance, opts: OnboardingOptions): Promise<void> {
  app.get(
    '/onboarding',
    route(
      'project.onboarding',
      'remote',
      'THE THREE READS A NEW AGENT MAKES AT THE START, MADE SMALL: the ten or so doors it actually uses, ' +
        'one sentence each and each sentence taken from the route\'s own description, plus which project it ' +
        'should work in and how that was worked out. It measures itself in characters and in estimated tokens, ' +
        'and when it is over budget it drops the least valuable part and names in `leftOut` what it dropped and ' +
        'the request that fetches it back. It answers DOORS AND THE PROJECT; GET /api/brief answers the state ' +
        'of the project and GET /api/project/bootstrap answers what is true of it, and this reply carries ' +
        'neither the brief\'s module list nor its open work nor its decisions. When a directory is named it also ' +
        'carries every live durable agent registered as starting in exactly that folder and, for each, the live ' +
        'session it is already answering in, which is what lets the session hook name an agent for a terminal whose ' +
        'environment says nothing. It starts with `owner`: while nobody has given the ' +
        "office's owner a name it says the office has no owner yet and gives the guide's address, which an agent " +
        'opens for the person or hands them; the agent never gives the name itself. ' +
        '`whereTheProjectIsNow` names GET /api/project/bootstrap, which is the first read for where the project is ' +
        'now.',
    ),
    async (req): Promise<Record<string, unknown>> => {
      const q = parse(onboardingQuery, req.query, 'The onboarding read takes no other options:')
      const claim = workspaceFrom(req)
      const directory = q.directory === undefined ? null : resolve(q.directory)
      const project = resolveProject(claim, directory)
      const projectId = project.id
      const workspace = projectId === null ? null : getWorkspace(projectId)

      // WHICH DURABLE AGENTS SAY THEIR SESSIONS START IN THIS EXACT FOLDER, by part (c) of
      // a decision. Read once, here, and carried in the reply the session hook
      // already makes, so the hook
      // needs no sixth request to learn who it might be.
      const startFolder = await theStartFolderReading(directory)

      const routes = opts.listRoutes()
      const doors: OnboardingDoor[] = ONBOARDING_DOORS.map((routeKey) => ({
        route: routeKey,
        what: sentenceForDoor(routeKey, routes),
      }))

      // ---- the body, then the ladder, and then the body's own size.
      const leftOut: { rung: string; what: string; ask: string }[] = []
      let carriedDoors = doors
      let carriedBecause = project.because

      const owner = theOwnerReading(`${opts.pageAddress(req)}/${THE_GUIDE_ADDRESS}`)
      const bodyNow = (): Record<string, unknown> => ({
        owner,
        project: {
          id: projectId,
          title: workspace === null ? null : workspace.title,
          howWorkedOut: carriedBecause,
          asked: { workspaceHeader: claim.stated, directory },
          note:
            projectId === null
              ? 'No project was worked out, so the doors below are answerable but every project-scoped read ' +
                'needs one named first.'
              : 'Every request you make should carry the project header named in `howWorkedOut`.',
        } satisfies OnboardingProject,
        startFolder,
        forAgents: theAgentsFolder(),
        // WHERE THE PROJECT IS NOW IS NOT THIS READ'S QUESTION, so it names the read that answers it
        // (problem NSOa-cFZLg66). `THE_FIRST_READ` in shared/onboarding.ts is the one place that says it.
        whereTheProjectIsNow: THE_FIRST_READ,
        doors: carriedDoors,
        leftOut,
        leftOutNote:
          leftOut.length === 0
            ? 'Nothing was left out of this read: it fits the budget whole.'
            : `${String(leftOut.length)} thing${leftOut.length === 1 ? ' was' : 's were'} left out to keep this ` +
              'read inside its budget, and each one names the request that fetches it back.',
      })

      const measure = (body: Record<string, unknown>): { characters: number; bytes: number; tokens: number } => {
        const text = JSON.stringify(body)
        return {
          characters: text.length,
          bytes: Buffer.byteLength(text, 'utf8'),
          tokens: tokensEstimatedFor(text.length),
        }
      }

      const fits = (): boolean => measure(bodyNow()).tokens <= ONBOARDING_TOKEN_BUDGET
      for (const rung of ONBOARDING_LADDER) {
        if (fits()) break
        if (rung.rung === 'door-sentences') {
          carriedDoors = carriedDoors.map((door) => ({ route: door.route, what: door.route }))
        } else {
          carriedBecause = carriedBecause.split('. ', 1)[0] ?? carriedBecause
        }
        leftOut.push({ ...rung })
      }

      // Two passes, because writing the count into the body changes the body's length by the digits
      // of the count; the second pass measures the body the caller actually receives.
      const body = bodyNow()
      const first = measure(body)
      const size: OnboardingSize = {
        characters: first.characters,
        bytes: first.bytes,
        tokensEstimated: first.tokens,
        charsPerTokenAssumed: CHARS_PER_TOKEN,
        budgetTokensEstimated: ONBOARDING_TOKEN_BUDGET,
        fits: first.tokens <= ONBOARDING_TOKEN_BUDGET,
        tokensAreAnEstimate: theTokenEstimateSentence(),
      }
      const withSize = { ...body, size }
      const second = measure(withSize)
      size.characters = second.characters
      size.bytes = second.bytes
      size.tokensEstimated = second.tokens
      size.fits = second.tokens <= ONBOARDING_TOKEN_BUDGET
      return withSize
    },
  )

  /**
   * THE CHEAP FORM OF ONE KIND. The full route is `/kinds/:kind`; this one is a separate route
   * rather than a query parameter so that not one line of the file another supervisor's worker was
   * in this afternoon had to change.
   */
  app.get<{ Params: { kind: string } }>(
    '/kinds/:kind/compact',
    route('project.schema', 'remote', COMPACT_KIND_NOTE),
    async (req, reply): Promise<CompactKind | { error: string; kinds: readonly string[] }> => {
      const name = req.params.kind
      if (!Object.prototype.hasOwnProperty.call(KIND_SPECS, name)) {
        const suggestion = suggestKey(name, RECORD_KINDS)
        reply.status(404)
        return {
          error:
            `There is no record kind "${name}".` +
            (suggestion !== null ? ` Did you mean "${suggestion}"?` : '') +
            ` The kinds are: ${RECORD_KINDS.join(', ')}. GET /api/kinds describes all of them.`,
          kinds: RECORD_KINDS,
        }
      }
      return compactKindOf(KIND_SPECS[name as keyof typeof KIND_SPECS])
    },
  )
}

/**
 * WHERE AN AGENT'S TOOLS ARE, ON THE OFFICE'S OWN MACHINE. The skill names `<for-agents folder>` and
 * this is where it is: for-agents/ in a checkout, and in an installed office the same folder inside the
 * installation, run with the install's own Node (theInstallsNode in src/config/settings.mjs). It is the path on the machine this office
 * runs on; an agent on another machine fetches the waiter from `GET /api/handles/waiter` instead.
 *
 * `environment` is what a tool's start must set as well. On Linux the install's own Node is the app's own program, which
 * opens the app unless it is told to run as Node.
 */
function theAgentsFolder(): { folder: string; node: string; environment: Record<string, string>; tools: readonly string[]; note: string } {
  // Named, because an agent runs a tool later, in a process of its own: `node` on PATH from a checkout.
  const node = theInstallsNode({ named: true })
  return {
    folder: resolve(REPO_ROOT, THE_FOR_AGENTS_FOLDER),
    node: node.program,
    environment: node.environment,
    tools: THE_AGENTS_TOOLS,
    note:
      'A path on the machine this office runs on. Run a tool there as `<node> <folder>/<tool>`, with each variable in ' +
      '`environment` set; from another machine, fetch the waiter from GET /api/handles/waiter.',
  }
}
