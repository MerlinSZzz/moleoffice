/** The English of one fixed rule of labels and the roll: the rule's own sentence, read where the code keeps it. */
function theRuleSays(id: CastingLabelRule['id']): string {
  const rule = CASTING_LABEL_RULES.find((one) => one.id === id)
  if (rule === undefined) throw new Error(`src/shared/casting-label-rules.ts holds no rule "${id}" of labels and the roll.`)
  return rule.says
}
