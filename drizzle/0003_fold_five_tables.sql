-- The five tables that were created outside the migration system, brought inside it.
--
-- `panel_layouts`, `session_resources`, `source_files`, `source_index` and `source_file_hashes`
-- were each created by a `CREATE TABLE IF NOT EXISTS` running at import time, in the file that
-- owned the feature: `ensureLayoutTable()` in api/layout.ts, `ensureResourceTable()` in
-- lib/resources.ts and `ensureSourceIndexTables()` in lib/sourceindex.ts. All three functions and
-- all three call sites were DELETED in the same change that added this file. They had to go
-- together: two definitions of one table is this codebase's recurring defect written in SQL, and
-- it is the worst version of it, because it fails at runtime on INSERT rather than at compile
-- time — whichever writer reaches a new database first decides the shape and the other one finds
-- out in production.
--
-- What this file buys is a MIGRATION PATH. `CREATE TABLE IF NOT EXISTS` creates a table that is
-- missing and does nothing at all to one that is there, so until now adding a column to
-- `session_resources` had nowhere to go, and every database that already held the table would
-- never have got the column.
--
-- Generated by drizzle-kit from src/server/db/schema.ts, then edited BY HAND to add
-- `IF NOT EXISTS`, exactly as 0001 and 0002 were. Read the three notes below before changing
-- anything here.
--
-- WHY `IF NOT EXISTS` IS ADDED BY HAND, AND WHY IT IS ON THE INDEXES TOO.
-- drizzle-kit emits bare `CREATE TABLE` and bare `CREATE INDEX`. Every one of these five tables,
-- and both of the `session_resources` indexes, ALREADY EXIST in every database the deleted
-- `ensure*` functions ever touched — which is every database anybody has run this server against,
-- including ./data/panelx.db. A bare statement here would stop on `table panel_layouts already
-- exists` out of a command whose whole job is to be run again. This is the first migration where
-- the guard is not a precaution against a future writer: it is load-bearing today.
--
-- WHY THE GENERATED SQL WAS NOT TIDIED UP WHILE IT WAS OPEN.
-- `session_resources.id` and `source_index.workspace_id` are written `text PRIMARY KEY` with no
-- NOT NULL, because SQLite leaves a TEXT PRIMARY KEY nullable unless NOT NULL is spelt out and
-- that is exactly how the `ensure*` functions created them. Adding NOT NULL here would give new
-- databases a stricter table than the ones already on disk — one table with two shapes depending
-- on when the database was made, which is the same defect this change exists to remove, wearing a
-- different hat. Making the old ones match instead would mean rebuilding the table, and migrations
-- in this project never rewrite a row. See the comment on `sessionResources.id` in
-- src/server/db/schema.ts.
--
-- NOTHING BELOW TOUCHES AN EXISTING ROW. Five tables and two indexes are created if they are not
-- already there, and nothing else is read, rewritten, rebuilt or altered. No column is dropped,
-- renamed or retyped. A database that already has all five gains nothing but a journal row saying
-- this file ran; a database that has none of them gains five empty tables. Both were run before
-- this was committed, against a copy of ./data/panelx.db with 229 records, 117 links and 420
-- changes in it, and against a database built from 0000 forward.
